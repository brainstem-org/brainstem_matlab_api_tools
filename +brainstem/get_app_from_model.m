function app = get_app_from_model(modelname)
% GET_APP_FROM_MODEL  API app that serves a model: /api/<portal>/<app>/<model>/.
%
%   app = brainstem.get_app_from_model(MODEL) returns '' for an unknown model.
%
%   The list matches the server's REST resources, plus 'brainregion', the deprecated
%   name of 'anatomicalregion' that LOAD, SAVE and DELETE resolve with a warning.

switch modelname
    case {'breeding', 'cohort', 'cohortsubject', 'collection', 'collectionsession', 'epoch', ...
          'project', 'projectgroupmembershipinvitation', 'projectmembershipinvitation', 'session', ...
          'sessiondatastorage', 'specimen', 'specimenset', 'subject'}
        app = 'stem';
    case {'behavior', 'consumablestock', 'dataacquisition', 'dataacquisitioninterface', ...
          'dataacquisitionprocedure', 'dataacquisitiontemplate', 'episodepersonnel', 'equipment', ...
          'experimentalinterface', 'experimentalinterfacetemplate', 'manipulation', ...
          'manipulationinterface', 'manipulationtemplate', 'materialusage', ...
          'materialusagetemplate', 'procedure', 'procedureepisode', 'procedureepisodetemplate', ...
          'procedurelog', 'proceduretemplate', 'specimenlog', 'specimenprocedure', ...
          'specimenproceduretemplate', 'subjectlog'}
        app = 'modules';
    case {'behavioralassay', 'behavioralassaygroupmembershipinvitation', ...
          'behavioralassaymembershipinvitation', 'datastorage', ...
          'datastoragegroupmembershipinvitation', 'datastoragemembershipinvitation', 'inventory', ...
          'inventorygroupmembershipinvitation', 'inventorymembershipinvitation', 'license', ...
          'licensegroupmembershipinvitation', 'licensemembershipinvitation', 'protocol', ...
          'protocolgroupmembershipinvitation', 'protocolmembershipinvitation', 'setup', ...
          'setupgroupmembershipinvitation', 'setupmembershipinvitation'}
        app = 'personal_attributes';
    case {'consumable', 'consumableapproval', 'hardwaredevice', 'hardwaredeviceapproval', ...
          'supplier', 'supplierapproval'}
        app = 'resources';
    case {'anatomicalreference', 'anatomicalregion', 'behavioralcategory', ...
          'behavioralcategoryapproval', 'behavioralparadigm', 'behavioralparadigmapproval', ...
          'brainregion', 'coordinatetransform', 'regulatoryauthority', ...
          'regulatoryauthorityapproval', 'setuptype', 'setuptypeapproval', 'species', ...
          'speciesapproval', 'strain', 'strainapproval'}
        app = 'taxonomies';
    case {'journal', 'journalapproval', 'publication', 'publicationapproval'}
        app = 'dissemination';
    case {'admingroup', 'group', 'groupmembershipinvitation', 'groupmembershiprequest', ...
          'laboratory', 'pendinginvitation', 'user'}
        app = 'users';
    otherwise
        app = '';
end
